    print(f"🔍 Всего уникальных прокси для проверки: {len(candidates)}")
    print("⚡ Запуск асинхронного чекера с пингом к Twitch HTTPS (id.twitch.tv)...")

    # 3. Чекаем с параллелизмом 60 потоков
    sem = asyncio.Semaphore(60)
    tasks = [test_proxy(p, sem) for p in candidates]
    
    start_time = time.time()
    results = await asyncio.gather(*tasks, return_exceptions=True)
    elapsed = time.time() - start_time

    alive = [r for r in results if isinstance(r, dict) and r is not None]
