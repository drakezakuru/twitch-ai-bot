async def fetch_online_proxies() -> list[str]:
    """Скачивает свежие прокси из открытых онлайн-репозиториев."""
    found: list[str] = []
    print("🌐 Загрузка свежих бесплатных прокси из интернета...")
    async with httpx.AsyncClient(timeout=10.0, follow_redirects=True) as client:
        for proto, url in ONLINE_SOURCES:
            try:
                resp = await client.get(url)
                if resp.status_code == 200:
                    lines = resp.text.splitlines()[:100]  # берем топ 100 свежих с каждого источника
                    for l in lines:
                        l = l.strip()
                        if l and not l.startswith("#"):
                            if "://" not in l:
                                l = f"{proto}://{l}"
                            found.append(l)
                    print(f"  ✓ {proto.upper()}: загружено {len(lines)} из {url.split('/')[-1]}")
            except Exception as e:
                print(f"  ✗ Не удалось загрузить {url}: {e}")
    return found


async def test_proxy(proxy_url: str, sem: asyncio.Semaphore) -> dict[str, Any] | None:
    """Быстрый ping к Twitch HTTPS через указанный прокси."""
    async with sem:
        t0 = time.perf_counter()
        try:
            # Таймаут 4 сек на соединение и ответ
            async with httpx.AsyncClient(proxy=proxy_url, timeout=4.0, verify=False) as client:
                resp = await client.get("https://id.twitch.tv/oauth2/validate")
                latency_ms = (time.perf_counter() - t0) * 1000
                if resp.status_code in {200, 401, 400}:
                    status = "ok" if latency_ms < 1500 else "slow"
                    return {
                        "url": proxy_url,
                        "status": status,
                        "latency_ms": round(latency_ms, 1),
                    }
        except Exception:
            return None
    return None


