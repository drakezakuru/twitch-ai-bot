    print(f"\n🏁 Проверка завершена за {elapsed:.1f} сек!")
    print(f"✅ Живых и рабочих прокси: {len(alive)} из {len(candidates)}")

    if not alive:
        print("⚠️ Живых прокси не обнаружено (публичные прокси быстро умирают).")
